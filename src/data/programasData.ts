const getRolesFromProgram = (titulo: string, categoria: string): string[] => {
  const roles = [];
  const t = titulo.toLowerCase();
  if (t.includes('ingeniería') || t.includes('tic') || t.includes('tecnología') || t.includes('sistemas') || t.includes('ambiental')) {
    roles.push('Líder Técnico', 'Director de TI', 'Ingeniero Especialista');
  }
  if (t.includes('administración') || t.includes('gerencia') || t.includes('gestión') || t.includes('desarrollo territorial')) {
    roles.push('CEO', 'Gerente de Proyectos', 'Director Ejecutivo');
  }
  if (t.includes('educación') || t.includes('pedagogía') || t.includes('innovación educativa')) {
    roles.push('Rector', 'Director Académico', 'Investigador Educativo');
  }
  if (t.includes('medicina') || t.includes('biomédicas') || t.includes('farmacéuticas') || t.includes('odontología') || t.includes('enfermería') || t.includes('toxicología')) {
    roles.push('Director Médico', 'Investigador Científico', 'Auditor en Salud');
  }
  if (t.includes('derecho') || t.includes('políticas') || t.includes('público') || t.includes('fiscal')) {
    roles.push('Asesor Legal', 'Funcionario Público', 'Consultor Jurídico');
  }
  if (t.includes('ciencias') || t.includes('físicas') || t.includes('química') || t.includes('microbiología')) {
    roles.push('Investigador Científico', 'Director de Laboratorio');
  }
  
  if (roles.length === 0) {
    if (categoria === 'Doctorados') roles.push('Investigador Senior', 'Consultor Experto');
    else if (categoria === 'Maestrías') roles.push('Director de Área', 'Especialista Senior');
    else roles.push('Especialista Junior', 'Analista Senior');
  }
  // Dedup just in case
  return Array.from(new Set(roles));
};

export const CATALOGO_PROGRAMAS = Object.values(PROGRAMAS_DB).map((p) => ({
  id: p.id,
  titulo: p.titulo,
  categoria: p.categoria,
  facultad: p.facultad,
  modalidad: p.modalidad || 'Presencial',
  duracion: p.duracion || (p.categoria === 'Doctorados' ? '8 semestres' : p.categoria === 'Maestrías' ? '4 semestres' : '2 semestres'),
  inversion: p.inversion || 'Consultar',
  roles: getRolesFromProgram(p.titulo, p.categoria)
}));

